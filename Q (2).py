#(2) Write a Python Program to enter two nos. and perform all 5 mathematical operations
num1 = int(input("input 1st number :- "))
num2 = int(input("input 2nd number :- "))

#1st mathematical operations
sum = num1+num2
print("sum of two input = ",sum)

#2nd mathematical operations
abs = num1-num2
print("abs of two input = ",abs)

#3rd mathematical operations
subs = num1*num2
print("subs of two input = ",subs)

#4th mathematical operations
div = num1/num2
print("div of two input = ",div)

#4th mathematical operations
modulas = num1%num2
print("modulas of two input = ",modulas)