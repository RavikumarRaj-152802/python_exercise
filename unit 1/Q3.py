# Q. 3. Write a program to perform arithmetic relational and logical operations using Python operators.

a = 10
b = 5

# Arithmetic Operators

print("Arithmetic Operations:")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)

# Relational Operators

print("\nRelational Operations:")
print("a > b:", a > b)
print("a < b:", a < b)
print("a == b:", a == b)
print("a != b:", a != b)
print("a >= b:", a >= b)

# Logical Operators
x = True
y = False

print("\nLogical Operations:")
print("x and y:", x and y)
print("x or y:", x or y)
print("not x:", not x)