# Q.2. Write a program to illustrate the use of different data types and type casting.

a = 10
b = 3.14
c = "Hello Python"
d = True

# Displaying values and their data types

print("Integer:", a, type(a))
print("Float:", b, type(b))

print("String:", c, type(c))
print("Boolean:", d, type(d))

# Type casting
x = 10

print("Integer to float:", float(x))
print("Integer to string:", str(x))

y = "25"
print("String to integer:", int(y))

z = 5.8
print("Float to integer:", int(z))